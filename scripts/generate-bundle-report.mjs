#!/usr/bin/env node
/**
 * Runs `next build`, extracts the route size table, and writes docs/engagement/bundle-report.md.
 * For interactive treemaps: ANALYZE=true npm run build
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outPath = path.join(root, "docs/engagement/bundle-report.md");

const buildOutput = execSync("npm run build", {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 12 * 1024 * 1024,
  stdio: ["ignore", "pipe", "pipe"],
});

const routeLines = buildOutput
  .split("\n")
  .filter((line) => /^[├└]/.test(line.trim()) && (line.includes("○") || line.includes("ƒ")));

const generatedAt = new Date().toISOString().slice(0, 10);

const body = `# Bundle report (generated)

> Auto-generated by \`npm run analyze:bundle\` · ${generatedAt}

## How to inspect

\`\`\`bash
# Route table only (this file)
npm run analyze:bundle

# Interactive client/server treemap (opens in browser)
ANALYZE=true npm run build
\`\`\`

Treemap output: \`.next/analyze/client.html\` and \`.next/analyze/nodejs.html\` after an analyze build.

## App routes (latest \`next build\`)

| Route | Prerender |
|-------|-----------|
${routeLines
  .map((line) => {
    const trimmed = line.trim().replace(/^[^\s]+\s+/, "");
    const isDynamic = trimmed.startsWith("ƒ");
    const route = trimmed.replace(/^[○ƒ]\s+/, "").replace(/\s+[\d.]+[mhdys].*$/, "").trim();
    return `| \`${route}\` | ${isDynamic ? "dynamic (ƒ)" : "static (○)"} |`;
  })
  .join("\n")}

## Notes

- Heavy client routes: \`/tables/[tableId]\` (Coach Dock / Hand Insight dynamic imports), \`/me\`, homepage hub.
- Lobby APIs use slim \`/api/tables\` payloads (P12); SSE snapshots trimmed (P11).
- Re-run after large dependency or route changes.

`;

writeFileSync(outPath, body);
console.log(`Wrote ${outPath} (${routeLines.length} routes)`);
